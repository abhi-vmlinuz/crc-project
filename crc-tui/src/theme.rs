#[must_use]
pub fn get_theme(id_or_name: &str) -> &'static Theme {
    let lower = id_or_name.to_lowercase();
    THEMES
        .iter()
        .find(|t| t.id == lower || t.name.to_lowercase() == lower)
        .unwrap_or(&THEMES[0])
}

#[must_use]
pub fn theme_index(id_or_name: &str) -> usize {
    let lower = id_or_name.to_lowercase();
    THEMES
        .iter()
        .position(|t| t.id == lower || t.name.to_lowercase() == lower)
        .unwrap_or(0)
}
