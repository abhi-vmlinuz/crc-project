//! Theme catalogue, lifted from the rinode project so the two tools read as
//! one toolkit.
//!
//! `bg: None` keeps the terminal's own background, which matters in a lab where
//! the TUI may be launched inside an existing tmux pane or kitty window.

use ratatui::style::Color;

#[allow(dead_code)]
#[derive(Clone, Copy, Debug)]
pub struct Theme {
    pub id: &'static str,
    pub name: &'static str,
    pub bg: Option<Color>,
    pub accent: Color,
    pub secondary: Color,
    pub text: Color,
    pub muted: Color,
    pub comment: Color,
    pub green: Color,
    pub red: Color,
    pub yellow: Color,
    pub warning: Color,
}

impl Theme {
    #[allow(clippy::too_many_arguments)]
    pub const fn new(
        id: &'static str,
        name: &'static str,
        bg: Option<Color>,
        accent: Color,
        secondary: Color,
        text: Color,
        muted: Color,
        comment: Color,
        green: Color,
        red: Color,
        yellow: Color,
        warning: Color,
    ) -> Self {
        Self {
            id,
            name,
            bg,
            accent,
            secondary,
            text,
            muted,
            comment,
            green,
            red,
            yellow,
            warning,
        }
    }
}

