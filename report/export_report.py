#!/usr/bin/env python3
"""Generate a CRC calculation report (.tex) and compile it to PDF.

Mirrors web/crc.js exactly: same division, same frame, same verdict.
Usage:
    python3 export_report.py --message HELLO --gen 1011 --out report-hello
    python3 export_report.py --bits 1011001 --gen 1011 --flip 5 --out report-err
    python3 export_report.py --message abhishek --gen 1011 --out report-abhi --no-pdf
"""

import argparse
import subprocess
import sys
from pathlib import Path


def parse_bits(text):
    return [int(c) for c in text if c in "01"]


def text_to_bits(text):
    bits = []
    for byte in text.encode():
        for i in range(7, -1, -1):
            bits.append((byte >> i) & 1)
    return bits


def divide(message, gen):
    n = len(gen)
    work = message + [0] * (n - 1)
    augmented = work[:]
    steps = []
    for i in range(len(message)):
        xored = False
        if work[i] == 1:
            for j, g in enumerate(gen):
                work[i + j] ^= g
            xored = True
        steps.append((i, xored, work[:]))
    return work[len(message):], steps, augmented


def check_frame(received, gen):
    n = len(gen)
    work = received[:]
    for i in range(len(received) - n + 1):
        if work[i] == 1:
            for j, g in enumerate(gen):
                work[i + j] ^= g
    remainder = work[-(n - 1):]
    return remainder, all(b == 0 for b in remainder)


def tex_escape(text):
    return "".join(f"\\{c}" if c in "\\_{}$&#%^~" else c for c in text)


def build_tex(label, data, gen, crc, frame, received, damaged, remainder, valid, steps, augmented):
    b2s = lambda b: "".join(map(str, b))  # noqa: E731
    rows = "\n".join(
        f"    {i} & {'$\\oplus$' if xored else '---'} & \\texttt{{{b2s(bits)}}} \\\\"
        for i, xored, bits in steps
    )
    verdict = "VALID --- no error" if valid else "ERROR DETECTED"
    outcome = (
        "Remainder is all zero, so the frame arrived intact."
        if valid
        else "Remainder is non-zero, so at least one bit was changed in transit."
    )
    return f"""\\documentclass[11pt,a4paper]{{article}}
\\usepackage[margin=2cm]{{geometry}}
\\usepackage{{amsmath}}
\\usepackage{{array}}
\\usepackage{{booktabs}}
\\usepackage[T1]{{fontenc}}
\\usepackage{{lmodern}}
\\title{{CRC Lab --- Calculation Report}}
\\author{{Generated by CRC Lab}}
\\date{{\\today}}
\\begin{{document}}
\\maketitle

\\section{{Inputs}}
\\begin{{tabular}}{{ll}}
\\toprule
Message & \\texttt{{{tex_escape(label)}}} \\\\
Data bits & \\texttt{{{b2s(data)}}} ({len(data)} bits) \\\\
Generator & \\texttt{{{b2s(gen)}}} ({len(gen)} bits) \\\\
Appended zeros & {len(gen) - 1} \\\\
\\bottomrule
\\end{{tabular}}

\\section{{Sender: polynomial long division}}
Augmented dividend (data + {len(gen) - 1} zeros):
\\begin{{center}}\\texttt{{{b2s(augmented)}}}\\end{{center}}
Generator: \\texttt{{{b2s(gen)}}}. At each step a leading $1$ is cancelled by XOR with the generator ($\\oplus$ marks such a step):
\\begin{{center}}
\\footnotesize
\\begin{{tabular}}{{rcl}}
\\toprule
step & xor & register after step \\\\
\\midrule
{rows}
\\bottomrule
\\end{{tabular}}
\\end{{center}}

\\section{{Transmitted frame}}
CRC remainder: \\texttt{{{b2s(crc)}}}. Frame = data + CRC:
\\begin{{center}}\\texttt{{{b2s(frame)}}} ({len(frame)} bits)\\end{{center}}

\\section{{Receiver verification}}
Received frame: \\texttt{{{b2s(received)}}}. Flipped bit positions: {", ".join(map(str, damaged)) if damaged else "none"}.
Dividing by \\texttt{{{b2s(gen)}}} gives remainder \\texttt{{{b2s(remainder)}}}.
\\begin{{center}}\\textbf{{{verdict}}}\\end{{center}}
{outcome}

\\end{{document}}
"""


def main():
    ap = argparse.ArgumentParser(description="CRC report exporter")
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--message", help="text message, e.g. abhishek")
    src.add_argument("--bits", help="raw data bits, e.g. 1011001")
    ap.add_argument("--gen", required=True, help="generator bits, e.g. 1011")
    ap.add_argument("--flip", default="", help="comma-separated bit positions to flip")
    ap.add_argument("--out", required=True, help="output stem (no extension)")
    ap.add_argument("--no-pdf", action="store_true", help="skip pdflatex, .tex only")
    args = ap.parse_args()

    if args.message is not None:
        label = args.message
        if not (1 <= len(label) <= 12):
            sys.exit("message must be 1-12 characters")
        data = text_to_bits(label)
    else:
        label = args.bits
        if not label or not set(label) <= {"0", "1"} or len(label) > 64:
            sys.exit("bits must be 1-64 chars of 0/1")
        data = parse_bits(label)

    gen = parse_bits(args.gen)
    if len(gen) < 2 or len(gen) > 17 or gen[0] != 1 or gen[-1] != 1:
        sys.exit("generator must be 2-17 bits starting and ending with 1")

    crc, steps, augmented = divide(data, gen)
    frame = data + crc
    received = frame[:]
    damaged = []
    if args.flip.strip():
        for p in args.flip.split(","):
            pos = int(p.strip())
            if not 0 <= pos < len(frame):
                sys.exit(f"flip position {pos} out of range 0..{len(frame) - 1}")
            received[pos] ^= 1
            damaged.append(pos)
    damaged.sort()
    remainder, valid = check_frame(received, gen)

    tex = build_tex(label, data, gen, crc, frame, received, damaged, remainder, valid, steps, augmented)
    out = Path(args.out)
    tex_path = out.with_suffix(".tex")
    tex_path.write_text(tex)
    print(f"wrote {tex_path}")

    if not args.no_pdf:
        for _ in range(2):
            r = subprocess.run(
                ["pdflatex", "-interaction=nonstopmode", tex_path.name],
                cwd=tex_path.parent,
                capture_output=True,
                text=True,
            )
        log = (tex_path.parent / (tex_path.stem + ".log")).read_text(errors="replace")
        errors = [line for line in log.splitlines() if line.startswith("!")]
        if errors or r.returncode != 0:
            print("pdflatex errors:")
            print("\n".join(errors[:10]) or r.stderr[-2000:])
            sys.exit(1)
        print(f"wrote {out.with_suffix('.pdf')}")


if __name__ == "__main__":
    main()
