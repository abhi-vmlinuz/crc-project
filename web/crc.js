function texEscape(text) {
  return String(text).replace(/([\\_{}$&#%^~])/g, '\\$1');
}

/**
 * Build a complete LaTeX document for the current computation.
 * Same content the Python exporter produces, so web download and compiled
 * PDF never disagree.
 */
export function buildTexReport({
  messageLabel,
  dataBits,
  genBits,
  crcBits,
  frame,
  received,
  damaged,
  receiverRemainder,
  valid,
  divSteps,
  divAugmented,
}) {
  const b2s = (b) => b.join('');
  const stepRows = divSteps
    .map((s) => `    ${s.index} & ${(s.xored ? '$\\oplus$' : '---')} & \\texttt{${b2s(s.bits)}} \\\\`)
    .join('\n');
  const verdict = valid ? 'VALID --- no error' : 'ERROR DETECTED';
  const damagedStr = damaged.length ? damaged.join(', ') : 'none';
  return `\\documentclass[11pt,a4paper]{article}
\\usepackage[margin=2cm]{geometry}
\\usepackage{amsmath}
\\usepackage{array}
\\usepackage{booktabs}
\\usepackage[T1]{fontenc}
\\usepackage{lmodern}
\\title{CRC Lab --- Calculation Report}
\\author{Generated by CRC Lab}
\\date{\\today}
\\begin{document}
\\maketitle

\\section{Inputs}
\\begin{tabular}{ll}
\\toprule
Message & \\texttt{${texEscape(messageLabel)}} \\\\
Data bits & \\texttt{${b2s(dataBits)}} (${dataBits.length} bits) \\\\
Generator & \\texttt{${b2s(genBits)}} (${genBits.length} bits) \\\\
Appended zeros & ${genBits.length - 1} \\\\
\\bottomrule
\\end{tabular}

\\section{Sender: polynomial long division}
Augmented dividend (data + ${genBits.length - 1} zeros):
\\begin{center}\\texttt{${b2s(divAugmented)}}\\end{center}
Generator: \\texttt{${b2s(genBits)}}. At each step a leading $1$ is cancelled by XOR with the generator ($\\oplus$ marks such a step):
\\begin{center}
\\footnotesize
\\begin{tabular}{rcl}
\\toprule
step & xor & register after step \\\\
\\midrule
${stepRows}
\\bottomrule
\\end{tabular}
\\end{center}

\\section{Transmitted frame}
CRC remainder: \\texttt{${b2s(crcBits)}}. Frame = data + CRC:
\\begin{center}\\texttt{${b2s(frame)}} (${frame.length} bits)\\end{center}

\\section{Receiver verification}
Received frame: \\texttt{${b2s(received)}}. Flipped bit positions: ${damagedStr}.
Dividing by \\texttt{${b2s(genBits)}} gives remainder \\texttt{${b2s(receiverRemainder)}}.
\\begin{center}\\textbf{${verdict}}\\end{center}
${valid ? 'Remainder is all zero, so the frame arrived intact.' : 'Remainder is non-zero, so at least one bit was changed in transit.'}

\\end{document}
`;
}
