/**
 * Textbook CRC — the exact algorithm taught in class.
 *
 * 1. Take data bits D and generator G (length n).
 * 2. Append (n-1) zero bits to D.
 * 3. Divide by G using XOR (mod-2 division). The leftover (n-1) bits are the CRC.
 * 4. Transmitted frame = D + CRC.
 * 5. Receiver divides what arrives by G. Remainder all-zero = VALID, else ERROR.
 *
 * No catalogue, no reflection, no presets. ~100 lines, explainable in viva.
 */

/** Expand bytes to MSB-first bits. */
export function bytesToBits(bytes) {
  const bits = [];
  for (const byte of bytes) {
    for (let i = 7; i >= 0; i -= 1) bits.push((byte >> i) & 1);
  }
  return bits;
}

/** Text → bits via UTF-8/ASCII bytes. */
export function textToBits(text) {
  return bytesToBits(new TextEncoder().encode(text));
}

/** Keep only 0/1, drop everything else. */
export function parseBits(text) {
  const bits = [];
  for (const ch of String(text)) {
    if (ch === '0' || ch === '1') bits.push(Number(ch));
  }
  return bits;
}

export function bitsToString(bits) {
  return bits.map(String).join('');
}

/** True when the string is non-empty and all 0/1. */
export function validBits(text, minLen, maxLen) {
  const s = String(text).trim();
  if (s.length < minLen || s.length > maxLen) return false;
  return /^[01]+$/.test(s);
}

/**
 * Mod-2 division. Returns { remainder, steps } where each step is
 * { index, xored, bits } — the working register after that step.
 */
export function divide(messageBits, generatorBits) {
  const n = generatorBits.length;
  const work = [...messageBits, ...new Array(n - 1).fill(0)];
  const steps = [];
  const limit = messageBits.length;
  for (let i = 0; i < limit; i += 1) {
    let xored = false;
    if (work[i] === 1) {
      for (let j = 0; j < n; j += 1) work[i + j] ^= generatorBits[j];
      xored = true;
    }
    steps.push({ index: i, xored, bits: work.slice() });
  }
  return { remainder: work.slice(limit), steps, augmented: [...messageBits, ...new Array(n - 1).fill(0)] };
}

/** Transmitted frame = data + CRC remainder. */
export function buildFrame(dataBits, generatorBits) {
  const { remainder } = divide(dataBits, generatorBits);
  return { dataBits: dataBits.slice(), crcBits: remainder, frame: [...dataBits, ...remainder] };
}

/** Receiver check: divide received frame by G, valid when remainder is all zero. */
export function checkFrame(receivedBits, generatorBits) {
  const n = generatorBits.length;
  const work = receivedBits.slice();
  // Divide the whole received frame (data + crc) — no extra zeros appended.
  const steps = [];
  const limit = receivedBits.length - n + 1;
  for (let i = 0; i < limit; i += 1) {
    let xored = false;
    if (work[i] === 1) {
      for (let j = 0; j < n; j += 1) work[i + j] ^= generatorBits[j];
      xored = true;
    }
    steps.push({ index: i, xored, bits: work.slice() });
  }
  const remainder = work.slice(-(n - 1));
  const valid = remainder.every((b) => b === 0);
  return { valid, remainder, steps };
}

